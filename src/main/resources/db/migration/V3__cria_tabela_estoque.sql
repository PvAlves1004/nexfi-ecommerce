CREATE TABLE mov_estoque (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	data TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
	motivo TEXT,
	quantidade INT NOT NULL CHECK (quantidade>0),
	quantidade_restante INT ,
	tipo VARCHAR(24) NOT NULL CHECK (tipo IN ('ENTRADA', 'SAIDA', 'AJUSTE_ENTRADA', 'AJUSTE_SAIDA')),
	custo_unitario NUMERIC(10,2) CHECK (custo_unitario >=0),
	produto_id BIGINT NOT NULL,
	CONSTRAINT fk_mov_estoque_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
	CONSTRAINT ck_mov_estoque_saldo CHECK (
		quantidade_restante IS NULL
		OR (quantidade_restante >= 0 AND quantidade_restante <= quantidade)
		),
		
	CONSTRAINT ck_mov_estoque_lote CHECK (
		(tipo IN('ENTRADA', 'AJUSTE_ENTRADA')
			AND custo_unitario IS NOT NULL
			AND quantidade_restante IS NOT NULL)
		OR
		(tipo IN('SAIDA', 'AJUSTE_SAIDA')
			AND custo_unitario IS NULL
			AND quantidade_restante IS NULL)		
	),
	
	CONSTRAINT ck_mov_estoque_motivo CHECK (
		(tipo NOT IN('AJUSTE_ENTRADA', 'AJUSTE_SAIDA'))
		OR motivo IS NOT NULL)
		
);

CREATE TABLE controle_lotes (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	saida_id BIGINT NOT NULL,
	lote_id BIGINT NOT NULL,
	quantidade INT NOT NULL CHECK (quantidade>0),
	CONSTRAINT fk_controle_lotes_saida FOREIGN KEY (saida_id) REFERENCES mov_estoque (id),
	CONSTRAINT fk_controle_lotes_lote FOREIGN KEY (lote_id) REFERENCES mov_estoque (id)
);

